/**
 * ContextBridge Markdown Exporter
 * Generates human-readable, portable Markdown documentation for briefs and project state.
 */

export function exportBriefToMarkdown(brief, conversation = null) {
  if (!brief) return '';

  const parts = [];
  const dateStr = new Date(brief.updatedAt || Date.now()).toISOString().split('T')[0];

  parts.push(`# Continuation Brief: ${brief.title || 'AI Project Context'}`);
  parts.push(`*Generated by ContextBridge on ${dateStr} · Mode: ${brief.mode || 'balanced'} · Est. Tokens: ~${brief.sizeEstimate || 0}*`);
  parts.push('');

  if (conversation) {
    parts.push(`> **Source Details**: Provider: \`${conversation.provider || 'AI Chat'}\` | Messages: ${conversation.messages?.length || 0} | Capture Method: \`${conversation.captureMethod || 'manual'}\``);
    parts.push('');
  }

  // Project Milestones (if present)
  if (brief.milestones && brief.milestones.length > 0) {
    parts.push(`## 📌 Project Milestones Timeline`);
    brief.milestones.forEach(m => {
      parts.push(`- **${m.title}** [${m.category}]: ${m.summary}`);
    });
    parts.push('');
  }

  // Active Sections
  const includedSections = (brief.sections || []).filter(s => s.included && s.content && s.content.trim());
  includedSections.forEach(sec => {
    parts.push(`## ${sec.title}`);
    parts.push(sec.content.trim());
    parts.push('');
  });

  parts.push('---');
  parts.push('*Exported from ContextBridge. Ready to be pasted or attached to any LLM session.*');

  return parts.join('\n');
}
